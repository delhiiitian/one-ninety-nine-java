// 1.1 Hello, World
// Run: java HelloWorld.java

// Every Java program lives inside a class.
// The file name must match the public class name: HelloWorld.java
public class HelloWorld {

    // main is the front door. The JVM starts running your program here.
    public static void main(String[] args) {
        System.out.println("Hello, World!");          // prints a line and moves to the next line
        System.out.print("Java is ");                  // print does NOT add a new line
        System.out.print("fun ");
        System.out.println("and friendly.");
        System.out.println("Welcome to Java 199.");
    }
}
